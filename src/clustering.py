"""
Clustering and dimensionality-reduction analysis for the Greek New Testament.

This module uses linguistic features generated by features.py to explore
relationships between New Testament books without supplying authorship labels
to the clustering algorithms.

Supported analyses:

    - Hierarchical clustering
    - Dendrogram generation
    - Principal Component Analysis (PCA)
    - PCA scatter plots
    - Feature-family-specific clustering
    - Whole-book analysis
    - Fixed-token-window analysis
    - Pauline-only window analysis
    - CSV export of PCA coordinates and cluster assignments

Important:
    Clustering is descriptive. It does not establish authorship.

    Results may be influenced by:

        - genre
        - subject matter
        - audience
        - text length
        - quotations
        - editorial activity
        - scribal/amanuensis involvement
        - feature selection
        - window size
        - normalization method
"""

