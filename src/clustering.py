# ---------------------------------------------------------------------------
# Hierarchical clustering
# ---------------------------------------------------------------------------

def hierarchical_clustering(
    matrix: pd.DataFrame,
    method: str = "ward",
):
    """
    Perform hierarchical clustering.

    Parameters
    ----------
    matrix:
        Standardized numerical feature matrix.

    method:
        scipy linkage method.

        Common choices:

            ward
            average
            complete
            single

    Returns
    -------
    numpy.ndarray
        Linkage matrix.
    """

    return linkage(
        matrix.to_numpy(),
        method=method,
    )


# ---------------------------------------------------------------------------
# Cluster assignments
# ---------------------------------------------------------------------------

def cluster_assignments(
    matrix: pd.DataFrame,
    linkage_matrix,
    n_clusters: int = 5,
) -> pd.DataFrame:
    """
    Assign samples to a requested number of hierarchical clusters.
    """

    clusters = fcluster(
        linkage_matrix,
        t=n_clusters,
        criterion="maxclust",
    )

    result = pd.DataFrame(
        {
            "sample": matrix.index,
            "cluster": clusters,
        }
    )

    result = result.sort_values(
        ["cluster", "sample"]
    )

    return result


# ---------------------------------------------------------------------------
# Dendrogram
# ---------------------------------------------------------------------------

def plot_dendrogram(
    matrix: pd.DataFrame,
    linkage_matrix,
    title: str,
    output_file: Path,
    figsize: tuple[int, int] = (14, 10),
) -> None:
    """
    Generate and save a hierarchical-clustering dendrogram.
    """

    plt.figure(
        figsize=figsize
    )

    dendrogram(
        linkage_matrix,
        labels=matrix.index.tolist(),
        orientation="right",
        leaf_font_size=9,
    )

    plt.title(title)
    plt.xlabel("Distance")
    plt.ylabel("Sample")

    plt.tight_layout()

    plt.savefig(
        output_file,
        dpi=200,
        bbox_inches="tight",
    )

    plt.close()


# ---------------------------------------------------------------------------
# PCA
# ---------------------------------------------------------------------------

def run_pca(
    matrix: pd.DataFrame,
    components: int = 2,
) -> tuple[pd.DataFrame, PCA]:
    """
    Perform Principal Component Analysis.

    Returns:

        PCA coordinates
        fitted PCA model
    """

    max_components = min(
        components,
        matrix.shape[0],
        matrix.shape[1],
    )

    pca = PCA(
        n_components=max_components
    )

    transformed = pca.fit_transform(
        matrix
    )

    columns = [
        f"PC{i + 1}"
        for i in range(max_components)
    ]

    coordinates = pd.DataFrame(
        transformed,
        index=matrix.index,
        columns=columns,
    )

    return coordinates, pca


# ---------------------------------------------------------------------------
# PCA plot: books
# ---------------------------------------------------------------------------

def plot_book_pca(
    coordinates: pd.DataFrame,
    pca: PCA,
    title: str,
    output_file: Path,
) -> None:
    """
    Plot whole-book PCA coordinates.
    """

    if "PC1" not in coordinates.columns:
        return

    if "PC2" not in coordinates.columns:
        return

    fig, ax = plt.subplots(
        figsize=(14, 10)
    )

    ax.scatter(
        coordinates["PC1"],
        coordinates["PC2"],
    )

    for book, row in coordinates.iterrows():

        ax.annotate(
            book,
            (
                row["PC1"],
                row["PC2"],
            ),
            xytext=(5, 5),
            textcoords="offset points",
            fontsize=8,
        )

    variance = (
        pca.explained_variance_ratio_
        * 100
    )

    ax.set_xlabel(
        f"PC1 ({variance[0]:.1f}% variance)"
    )

    ax.set_ylabel(
        f"PC2 ({variance[1]:.1f}% variance)"
    )

    ax.set_title(title)

    ax.axhline(
        0,
        linewidth=0.5,
    )

    ax.axvline(
        0,
        linewidth=0.5,
    )

    plt.tight_layout()

    plt.savefig(
        output_file,
        dpi=200,
        bbox_inches="tight",
    )

    plt.close()


# ---------------------------------------------------------------------------
# PCA plot: token windows
# ---------------------------------------------------------------------------

def plot_window_pca(
    coordinates: pd.DataFrame,
    metadata: pd.DataFrame,
    pca: PCA,
    title: str,
    output_file: Path,
    label_points: bool = False,
) -> None:
    """
    Plot PCA coordinates for fixed-token windows.

    Each point represents a window rather than an entire book.
    """

    if "PC1" not in coordinates.columns:
        return

    if "PC2" not in coordinates.columns:
        return

    plot_data = coordinates.join(
        metadata[["book"]]
    )

    fig, ax = plt.subplots(
        figsize=(14, 10)
    )

    # Plot each book independently so each book receives
    # a separate legend entry.

    for book, group in plot_data.groupby(
        "book"
    ):

        ax.scatter(
            group["PC1"],
            group["PC2"],
            label=book,
            alpha=0.7,
        )

        if label_points:

            for sample, row in group.iterrows():

                ax.annotate(
                    sample,
                    (
                        row["PC1"],
                        row["PC2"],
                    ),
                    xytext=(3, 3),
                    textcoords="offset points",
                    fontsize=6,
                )

    variance = (
        pca.explained_variance_ratio_
        * 100
    )

    ax.set_xlabel(
        f"PC1 ({variance[0]:.1f}% variance)"
    )

    ax.set_ylabel(
        f"PC2 ({variance[1]:.1f}% variance)"
    )

    ax.set_title(title)

    ax.axhline(
        0,
        linewidth=0.5,
    )

    ax.axvline(
        0,
        linewidth=0.5,
    )

    ax.legend(
        fontsize=7,
        bbox_to_anchor=(1.05, 1),
        loc="upper left",
    )

    plt.tight_layout()

    plt.savefig(
        output_file,
        dpi=200,
        bbox_inches="tight",
    )

    plt.close()


# ---------------------------------------------------------------------------
# PCA loadings
# ---------------------------------------------------------------------------

def pca_loadings(
    matrix: pd.DataFrame,
    pca: PCA,
) -> pd.DataFrame:
    """
    Return feature loadings for each principal component.

    This tells us which linguistic features are responsible for the
    separation visible in PCA.
    """

    columns = [
        f"PC{i + 1}"
        for i in range(
            pca.components_.shape[0]
        )
    ]

    loadings = pd.DataFrame(
        pca.components_.T,
        index=matrix.columns,
        columns=columns,
    )

    return loadings


def strongest_loadings(
    loadings: pd.DataFrame,
    component: str,
    n: int = 15,
) -> pd.DataFrame:
    """
    Return the strongest positive and negative features for a PCA component.

    The number of features selected from each side is automatically limited
    so the positive and negative groups cannot overlap when the feature family
    contains relatively few features.
    """

    if component not in loadings.columns:
        raise ValueError(
            f"Unknown PCA component: {component}"
        )

    values = loadings[
        component
    ]

    # Prevent overlap between the strongest positive and negative
    # feature sets for small feature families.

    n = min(
        n,
        len(values) // 2,
    )

    if n == 0:

        return pd.DataFrame(
            columns=[
                "feature",
                "loading",
            ]
        )

    positive = (
        values
        .sort_values(
            ascending=False
        )
        .head(n)
    )

    negative = (
        values
        .sort_values()
        .head(n)
    )

    result = pd.concat(
        [
            negative.rename("loading"),
            positive.rename("loading"),
        ]
    )

    result.index.name = "feature"

    return result.reset_index()


# ---------------------------------------------------------------------------
# Whole-book analysis
# ---------------------------------------------------------------------------

def analyze_books(
    features: pd.DataFrame,
    family: str,
    n_clusters: int = 5,
) -> None:
    """
    Run clustering and PCA on whole books for one feature family.
    """

    print()
    print(
        f"Whole books: {family}"
    )
    print("-" * 70)

    matrix = prepare_matrix(
        features,
        family=family,
        standardize=True,
    )

    print(
        f"{matrix.shape[0]} books x "
        f"{matrix.shape[1]} features"
    )

    # -------------------------------------------------------
    # Hierarchical clustering
    # -------------------------------------------------------

    linkage_matrix = (
        hierarchical_clustering(
            matrix,
            method="ward",
        )
    )

    assignments = cluster_assignments(
        matrix,
        linkage_matrix,
        n_clusters=n_clusters,
    )

    assignments.to_csv(
        OUTPUT_DIR
        / f"book_clusters_{family}.csv",
        index=False,
    )

    plot_dendrogram(
        matrix,
        linkage_matrix,
        title=(
            "Greek New Testament "
            f"Hierarchical Clustering: {family}"
        ),
        output_file=(
            PLOT_DIR
            / f"book_dendrogram_{family}.png"
        ),
    )

    # -------------------------------------------------------
    # PCA
    # -------------------------------------------------------

    coordinates, pca = run_pca(
        matrix,
        components=5,
    )

    coordinates.to_csv(
        OUTPUT_DIR
        / f"book_pca_{family}.csv"
    )

    loadings = pca_loadings(
        matrix,
        pca,
    )

    loadings.to_csv(
        OUTPUT_DIR
        / f"book_pca_loadings_{family}.csv"
    )

    plot_book_pca(
        coordinates,
        pca,
        title=(
            "Greek New Testament PCA: "
            f"{family}"
        ),
        output_file=(
            PLOT_DIR
            / f"book_pca_{family}.png"
        ),
    )

    variance = (
        pca.explained_variance_ratio_
        * 100
    )

    print(
        "Explained variance:"
    )

    for i, value in enumerate(
        variance,
        start=1,
    ):

        print(
            f"  PC{i}: {value:.2f}%"
        )

    if "PC1" in loadings.columns:

        strongest = strongest_loadings(
            loadings,
            "PC1",
            n=10,
        )

        print()
        print(
            "Strongest PC1 features:"
        )

        print(
            strongest.to_string(
                index=False,
                formatters={
                    "loading":
                        lambda x: f"{x:.4f}"
                },
            )
        )


# ---------------------------------------------------------------------------
# Window analysis
# ---------------------------------------------------------------------------

def analyze_windows(
    window_features: pd.DataFrame,
    metadata: pd.DataFrame,
    family: str,
    n_clusters: int = 10,
) -> None:
    """
    Run clustering and PCA on fixed-token windows.
    """

    print()
    print(
        f"Token windows: {family}"
    )
    print("-" * 70)

    matrix = prepare_matrix(
        window_features,
        family=family,
        standardize=True,
    )

    print(
        f"{matrix.shape[0]} windows x "
        f"{matrix.shape[1]} features"
    )

    # -------------------------------------------------------
    # Hierarchical clustering
    # -------------------------------------------------------

    linkage_matrix = (
        hierarchical_clustering(
            matrix,
            method="ward",
        )
    )

    assignments = cluster_assignments(
        matrix,
        linkage_matrix,
        n_clusters=n_clusters,
    )

    assignments = (
        assignments
        .set_index("sample")
        .join(metadata)
        .reset_index()
    )

    assignments.to_csv(
        OUTPUT_DIR
        / f"window_clusters_{family}.csv",
        index=False,
    )

    # Window dendrograms are large, but they allow us to see whether
    # windows from the same book naturally remain near one another.

    plot_dendrogram(
        matrix,
        linkage_matrix,
        title=(
            f"{DEFAULT_WINDOW_SIZE}-Token "
            "Greek NT Windows: "
            f"{family}"
        ),
        output_file=(
            PLOT_DIR
            / f"window_dendrogram_{family}.png"
        ),
        figsize=(16, 30),
    )

    # -------------------------------------------------------
    # PCA
    # -------------------------------------------------------

    coordinates, pca = run_pca(
        matrix,
        components=5,
    )

    coordinates_with_metadata = (
        coordinates.join(
            metadata
        )
    )

    coordinates_with_metadata.to_csv(
        OUTPUT_DIR
        / f"window_pca_{family}.csv"
    )

    loadings = pca_loadings(
        matrix,
        pca,
    )

    loadings.to_csv(
        OUTPUT_DIR
        / f"window_pca_loadings_{family}.csv"
    )

    plot_window_pca(
        coordinates,
        metadata,
        pca,
        title=(
            f"{DEFAULT_WINDOW_SIZE}-Token "
            "Greek NT PCA: "
            f"{family}"
        ),
        output_file=(
            PLOT_DIR
            / f"window_pca_{family}.png"
        ),
        label_points=False,
    )

    variance = (
        pca.explained_variance_ratio_
        * 100
    )

    print(
        "Explained variance:"
    )

    for i, value in enumerate(
        variance,
        start=1,
    ):

        print(
            f"  PC{i}: {value:.2f}%"
        )


# ---------------------------------------------------------------------------
# Pauline-only window PCA
# ---------------------------------------------------------------------------

def analyze_pauline_windows(
    window_features: pd.DataFrame,
    metadata: pd.DataFrame,
    family: str = "style",
) -> None:
    """
    Perform PCA using only windows from the traditionally Pauline corpus.

    The traditional Pauline list is used only to select the corpus being
    examined. Authorship categories are not supplied to PCA.
    """

    paul_samples = metadata[
        metadata["book"].isin(
            PAULINE_BOOKS
        )
    ].index

    paul_features = window_features.loc[
        paul_samples
    ]

    paul_metadata = metadata.loc[
        paul_samples
    ]

    matrix = prepare_matrix(
        paul_features,
        family=family,
        standardize=True,
    )

    print(
        f"  {matrix.shape[0]} windows x "
        f"{matrix.shape[1]} features"
    )

    coordinates, pca = run_pca(
        matrix,
        components=5,
    )

    coordinates.join(
        paul_metadata
    ).to_csv(
        OUTPUT_DIR
        / f"pauline_window_pca_{family}.csv"
    )

    loadings = pca_loadings(
        matrix,
        pca,
    )

    loadings.to_csv(
        OUTPUT_DIR
        / f"pauline_window_pca_loadings_{family}.csv"
    )

    plot_window_pca(
        coordinates,
        paul_metadata,
        pca,
        title=(
            "Pauline Corpus "
            f"{DEFAULT_WINDOW_SIZE}-Token PCA: "
            f"{family}"
        ),
        output_file=(
            PLOT_DIR
            / f"pauline_window_pca_{family}.png"
        ),
        label_points=False,
    )

    variance = (
        pca.explained_variance_ratio_
        * 100
    )

    print(
        "  Explained variance:"
    )

    for i, value in enumerate(
        variance,
        start=1,
    ):

        print(
            f"    PC{i}: {value:.2f}%"
        )


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:

    ensure_output_directories()

    print()
    print(
        "Greek New Testament Clustering Analysis"
    )
    print("=" * 80)

    # ------------------------------------------------------------------
    # Load
    # ------------------------------------------------------------------

    print()
    print(
        "Loading Greek New Testament..."
    )

    nt = load_new_testament()

    print(
        f"Loaded {len(nt):,} tokens."
    )

    print(
        "Expanding morphology..."
    )

    nt = expand_morphology(
        nt
    )

    # ------------------------------------------------------------------
    # Whole-book features
    # ------------------------------------------------------------------

    print()
    print(
        "Building whole-book feature matrix..."
    )

    book_features = build_feature_matrix(
        nt
    )

    # ------------------------------------------------------------------
    # Whole-book analysis
    # ------------------------------------------------------------------

    print()
    print("=" * 80)
    print(
        "WHOLE-BOOK ANALYSIS"
    )
    print("=" * 80)

    for family in FEATURE_FAMILIES:

        analyze_books(
            book_features,
            family=family,
            n_clusters=5,
        )

    # ------------------------------------------------------------------
    # Token windows
    # ------------------------------------------------------------------

    print()
    print("=" * 80)
    print(
        "TOKEN-WINDOW ANALYSIS"
    )
    print("=" * 80)

    print()
    print(
        f"Building "
        f"{DEFAULT_WINDOW_SIZE}-token windows..."
    )

    window_features, metadata = (
        build_window_feature_matrix(
            nt,
            window_size=DEFAULT_WINDOW_SIZE,
            min_window_size=DEFAULT_MIN_WINDOW_SIZE,
        )
    )

    print(
        f"Generated "
        f"{len(window_features):,} windows."
    )

    # Save metadata because it is useful when interpreting
    # individual PCA points and clusters.

    metadata.to_csv(
        OUTPUT_DIR
        / "window_metadata.csv"
    )

    # ------------------------------------------------------------------
    # Analyze token windows
    # ------------------------------------------------------------------

    for family in FEATURE_FAMILIES:

        analyze_windows(
            window_features,
            metadata,
            family=family,
            n_clusters=10,
        )

    # ------------------------------------------------------------------
    # Pauline-only analysis
    # ------------------------------------------------------------------

    print()
    print("=" * 80)
    print(
        "PAULINE WINDOW ANALYSIS"
    )
    print("=" * 80)

    for family in [
        "morphology",
        "function_words",
        "part_of_speech",
        "style",
        "combined",
    ]:

        print()
        print(
            f"Analyzing Pauline corpus: "
            f"{family}"
        )

        analyze_pauline_windows(
            window_features,
            metadata,
            family=family,
        )

    # ------------------------------------------------------------------
    # Finish
    # ------------------------------------------------------------------

    print()
    print("=" * 80)

    print(
        "Analysis complete."
    )

    print(
        f"CSV results:\n"
        f"    {OUTPUT_DIR}"
    )

    print(
        f"\nPlots:\n"
        f"    {PLOT_DIR}"
    )


if __name__ == "__main__":
    main()